-- V1__init.sql — initial schema for AI Professor Assistant
-- Compatible with PostgreSQL 15+ (and Supabase) and H2 in PostgreSQL mode.

CREATE TABLE app_user (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(255)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name    VARCHAR(100)  NOT NULL,
    role         VARCHAR(20)   NOT NULL,
    created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_app_user_email ON app_user (email);

ALTER TABLE app_user
    ADD CONSTRAINT ck_app_user_role CHECK (role IN ('STUDENT', 'TEACHER', 'ADMIN'));
