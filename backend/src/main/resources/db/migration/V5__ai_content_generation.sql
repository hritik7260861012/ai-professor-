ALTER TABLE generated_content
    ADD CONSTRAINT fk_content_unit FOREIGN KEY (unit_id) REFERENCES syllabus_unit (id);
ALTER TABLE generated_content
    ADD CONSTRAINT fk_content_reviewer FOREIGN KEY (reviewed_by) REFERENCES app_user (id);

