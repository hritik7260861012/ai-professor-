    ADD CONSTRAINT ck_content_type CHECK (content_type IN (
        'UNIT_NOTES', 'TEACHER_STUDY_MATERIAL', 'PPT_SLIDES',
        'ASSIGNMENTS_QUESTIONS', 'MCQS', 'QUICK_REVISION'));
ALTER TABLE generated_content
    ADD CONSTRAINT ck_content_language CHECK (language IN ('ENGLISH', 'HINDI', 'HINGLISH'));
ALTER TABLE generated_content
    ADD CONSTRAINT ck_content_audience CHECK (audience IN ('STUDENT', 'TEACHER'));
ALTER TABLE generated_content
    ADD CONSTRAINT ck_content_review_status CHECK (review_status IN (
        'DRAFT', 'IN_REVIEW', 'APPROVED', 'REJECTED', 'OUTDATED'));
