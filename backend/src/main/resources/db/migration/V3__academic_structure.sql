-- V3__academic_structure.sql -- Phase 3: academic structure
-- Additive only. V1 and V2 are never modified.
-- Compatible with PostgreSQL 15+ (and Supabase) and H2 in PostgreSQL mode.
--
-- Table "academic_class" is used because CLASS is a reserved SQL keyword.
--
-- Access scoping is enforced in the service layer (AcademicScopeService):
--   * teachers see only classes/subjects in teaching_assignment
--   * students see only classes in enrollment and their class_subject rows
--   * administrators see everything

-- ---------------------------------------------------------------- departments

CREATE TABLE department (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(20)  NOT NULL,
    name        VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_department_code ON department (code);
ALTER TABLE department
    ADD CONSTRAINT ck_department_code_upper CHECK (code = UPPER(code));

-- ------------------------------------------------------------------- programs

CREATE TABLE academic_program (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id  BIGINT       NOT NULL,
    code           VARCHAR(20)  NOT NULL,
    name           VARCHAR(150) NOT NULL,
    level          VARCHAR(20)  NOT NULL,
    duration_years INT          NOT NULL,
    description    VARCHAR(500),
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_academic_program_code ON academic_program (code);
CREATE INDEX idx_academic_program_department ON academic_program (department_id);

ALTER TABLE academic_program
    ADD CONSTRAINT fk_program_department FOREIGN KEY (department_id) REFERENCES department (id);
ALTER TABLE academic_program
    ADD CONSTRAINT ck_program_level CHECK (level IN ('UNDERGRADUATE', 'POSTGRADUATE'));
ALTER TABLE academic_program
    ADD CONSTRAINT ck_program_duration CHECK (duration_years BETWEEN 1 AND 10);

-- ------------------------------------------------------------ academic years

CREATE TABLE academic_year (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(20) NOT NULL,
    start_date DATE        NOT NULL,
    end_date   DATE        NOT NULL,
    is_current BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_academic_year_name ON academic_year (name);
ALTER TABLE academic_year
    ADD CONSTRAINT ck_academic_year_range CHECK (end_date > start_date);

-- ----------------------------------------------------------------- semesters

CREATE TABLE semester (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id BIGINT      NOT NULL,
    name             VARCHAR(60) NOT NULL,
    semester_number  INT         NOT NULL,
    start_date       DATE,
    end_date         DATE,
    created_at       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_semester_year_number ON semester (academic_year_id, semester_number);
CREATE INDEX idx_semester_year ON semester (academic_year_id);

ALTER TABLE semester
    ADD CONSTRAINT fk_semester_academic_year FOREIGN KEY (academic_year_id) REFERENCES academic_year (id);
ALTER TABLE semester
    ADD CONSTRAINT ck_semester_number CHECK (semester_number BETWEEN 1 AND 12);

-- ------------------------------------------------------------------ subjects

CREATE TABLE subject (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT       NOT NULL,
    program_id    BIGINT,
    code          VARCHAR(20)  NOT NULL,
    name          VARCHAR(150) NOT NULL,
    credits       INT          NOT NULL,
    description   VARCHAR(500),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_subject_code ON subject (code);
CREATE INDEX idx_subject_department ON subject (department_id);
CREATE INDEX idx_subject_program ON subject (program_id);

ALTER TABLE subject
    ADD CONSTRAINT fk_subject_department FOREIGN KEY (department_id) REFERENCES department (id);
ALTER TABLE subject
    ADD CONSTRAINT fk_subject_program FOREIGN KEY (program_id) REFERENCES academic_program (id);
ALTER TABLE subject
    ADD CONSTRAINT ck_subject_credits CHECK (credits BETWEEN 1 AND 12);

-- ------------------------------------------------------------------- classes

CREATE TABLE academic_class (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id  BIGINT       NOT NULL,
    semester_id BIGINT       NOT NULL,
    code        VARCHAR(30)  NOT NULL,
    name        VARCHAR(120) NOT NULL,
    capacity    INT          NOT NULL DEFAULT 60,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_class_semester_code ON academic_class (semester_id, code);
CREATE INDEX idx_class_program ON academic_class (program_id);
CREATE INDEX idx_class_semester ON academic_class (semester_id);

ALTER TABLE academic_class
    ADD CONSTRAINT fk_class_program FOREIGN KEY (program_id) REFERENCES academic_program (id);
ALTER TABLE academic_class
    ADD CONSTRAINT fk_class_semester FOREIGN KEY (semester_id) REFERENCES semester (id);
ALTER TABLE academic_class
    ADD CONSTRAINT ck_class_capacity CHECK (capacity BETWEEN 1 AND 1000);

-- Subjects offered in a class. semester_id is denormalised from the class so
-- that "subjects in semester X" is a single-index lookup; the service layer
-- always keeps it consistent with academic_class.semester_id.
CREATE TABLE class_subject (
    id          BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id    BIGINT    NOT NULL,
    subject_id  BIGINT    NOT NULL,
    semester_id BIGINT    NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_class_subject ON class_subject (class_id, subject_id);
CREATE INDEX idx_class_subject_subject ON class_subject (subject_id);
CREATE INDEX idx_class_subject_semester ON class_subject (semester_id);

ALTER TABLE class_subject
    ADD CONSTRAINT fk_class_subject_class FOREIGN KEY (class_id) REFERENCES academic_class (id);
ALTER TABLE class_subject
    ADD CONSTRAINT fk_class_subject_subject FOREIGN KEY (subject_id) REFERENCES subject (id);
ALTER TABLE class_subject
    ADD CONSTRAINT fk_class_subject_semester FOREIGN KEY (semester_id) REFERENCES semester (id);

-- ------------------------------------------------------- teaching assignments

-- A teacher may be assigned to any number of (class, subject, semester)
-- combinations. This is the authority for what a TEACHER can see.
CREATE TABLE teaching_assignment (
    id          BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id  BIGINT    NOT NULL,
    class_id    BIGINT    NOT NULL,
    subject_id  BIGINT    NOT NULL,
    semester_id BIGINT    NOT NULL,
    assigned_by BIGINT,
    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_teaching_assignment
    ON teaching_assignment (teacher_id, class_id, subject_id, semester_id);
CREATE INDEX idx_teaching_assignment_teacher ON teaching_assignment (teacher_id);
CREATE INDEX idx_teaching_assignment_class ON teaching_assignment (class_id);

ALTER TABLE teaching_assignment
    ADD CONSTRAINT fk_assignment_teacher FOREIGN KEY (teacher_id) REFERENCES app_user (id);
ALTER TABLE teaching_assignment
    ADD CONSTRAINT fk_assignment_class FOREIGN KEY (class_id) REFERENCES academic_class (id);
ALTER TABLE teaching_assignment
    ADD CONSTRAINT fk_assignment_subject FOREIGN KEY (subject_id) REFERENCES subject (id);
ALTER TABLE teaching_assignment
    ADD CONSTRAINT fk_assignment_semester FOREIGN KEY (semester_id) REFERENCES semester (id);
ALTER TABLE teaching_assignment
    ADD CONSTRAINT fk_assignment_assigner FOREIGN KEY (assigned_by) REFERENCES app_user (id);

-- --------------------------------------------------------------- enrollments

-- A student may be enrolled in any number of classes. This is the
-- authority for what a STUDENT can see.
CREATE TABLE enrollment (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  BIGINT      NOT NULL,
    class_id    BIGINT      NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'ENROLLED',
    enrolled_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_enrollment_student_class ON enrollment (student_id, class_id);
CREATE INDEX idx_enrollment_class ON enrollment (class_id);

ALTER TABLE enrollment
    ADD CONSTRAINT fk_enrollment_student FOREIGN KEY (student_id) REFERENCES app_user (id);
ALTER TABLE enrollment
    ADD CONSTRAINT fk_enrollment_class FOREIGN KEY (class_id) REFERENCES academic_class (id);
ALTER TABLE enrollment
    ADD CONSTRAINT ck_enrollment_status CHECK (status IN ('ENROLLED', 'DROPPED'));