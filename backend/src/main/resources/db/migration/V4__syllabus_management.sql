-- V4__syllabus_management.sql -- Phase 4: syllabus upload, extraction & review
-- Additive only. V1, V2 and V3 are never modified.
-- Compatible with PostgreSQL 15+ (and Supabase) and H2 in PostgreSQL mode.
--
-- Links to Phase 3 academic entities (academic_class, subject, semester)
-- rather than duplicating them. Authorisation is enforced in the service
-- layer: a teacher may only touch a syllabus for a (class, subject) pair
-- they hold a teaching_assignment for; students may only read APPROVED
-- rows for classes they are actively enrolled in.

-- ------------------------------------------------------------------ syllabus

CREATE TABLE syllabus (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Academic placement. semester_id mirrors academic_class.semester_id and
    -- is validated server-side, so it can never disagree with the class.
    class_id           BIGINT        NOT NULL,
    subject_id         BIGINT        NOT NULL,
    semester_id        BIGINT        NOT NULL,
    uploaded_by        BIGINT        NOT NULL,

    -- Original metadata, kept for display only. Never used to build a
    -- filesystem path; the random storage_key below is authoritative.
    original_filename  VARCHAR(255)  NOT NULL,
    content_type       VARCHAR(120)  NOT NULL,
    file_size          BIGINT        NOT NULL,
    storage_key        VARCHAR(120)  NOT NULL,
    checksum_sha256    VARCHAR(64),

    -- Lifecycle: UPLOADED -> EXTRACTING -> REVIEW_REQUIRED -> APPROVED,
    -- with EXTRACTION_FAILED (retryable) and REJECTED branches.
    status             VARCHAR(30)   NOT NULL DEFAULT 'UPLOADED',

    -- Re-uploading the same (class, subject, semester) creates a new version
    -- instead of overwriting, so history and the original file survive.
    version            INT           NOT NULL DEFAULT 1,
    is_current         BOOLEAN       NOT NULL DEFAULT TRUE,

    -- Preserved so the teacher can correct imperfect parsing.
    extracted_text     TEXT,
    extraction_error   VARCHAR(500),
    -- Set when status = REJECTED; a safe, teacher-facing explanation.
    review_note        VARCHAR(1000),
    reviewed_by        BIGINT,
    reviewed_at        TIMESTAMP,

    uploaded_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_syllabus_storage_key ON syllabus (storage_key);
CREATE UNIQUE INDEX uk_syllabus_class_subject_semester_version
    ON syllabus (class_id, subject_id, semester_id, version);
CREATE INDEX idx_syllabus_class ON syllabus (class_id);
CREATE INDEX idx_syllabus_subject ON syllabus (subject_id);
CREATE INDEX idx_syllabus_status ON syllabus (status);
CREATE INDEX idx_syllabus_uploader ON syllabus (uploaded_by);

ALTER TABLE syllabus
    ADD CONSTRAINT fk_syllabus_class FOREIGN KEY (class_id) REFERENCES academic_class (id);
ALTER TABLE syllabus
    ADD CONSTRAINT fk_syllabus_subject FOREIGN KEY (subject_id) REFERENCES subject (id);
ALTER TABLE syllabus
    ADD CONSTRAINT fk_syllabus_semester FOREIGN KEY (semester_id) REFERENCES semester (id);
ALTER TABLE syllabus
    ADD CONSTRAINT fk_syllabus_uploader FOREIGN KEY (uploaded_by) REFERENCES app_user (id);
ALTER TABLE syllabus
    ADD CONSTRAINT fk_syllabus_reviewer FOREIGN KEY (reviewed_by) REFERENCES app_user (id);

ALTER TABLE syllabus
    ADD CONSTRAINT ck_syllabus_status CHECK (
        status IN ('UPLOADED', 'EXTRACTING', 'EXTRACTION_FAILED', 'REVIEW_REQUIRED',
                   'APPROVED', 'REJECTED'));
ALTER TABLE syllabus
    ADD CONSTRAINT ck_syllabus_content_type CHECK (
        content_type IN ('application/pdf',
                         'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
                         'text/plain'));
ALTER TABLE syllabus
    ADD CONSTRAINT ck_syllabus_file_size CHECK (file_size > 0);
ALTER TABLE syllabus
    ADD CONSTRAINT ck_syllabus_version CHECK (version >= 1);

-- ----------------------------------------------------------- syllabus units

CREATE TABLE syllabus_unit (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    syllabus_id BIGINT       NOT NULL,
    title       VARCHAR(255) NOT NULL,
    position    INT          NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Position is an ordering hint, not an identity. A UNIQUE constraint here
-- would break wholesale structure edits: Hibernate inserts the replacement
-- rows before deleting the orphans, so transient duplicates at the same
-- position are unavoidable. Uniqueness is instead guaranteed by the
-- parent's (syllabus_id, unit_id, topic_id) scoping.
CREATE INDEX idx_syllabus_unit_position ON syllabus_unit (syllabus_id, position);

ALTER TABLE syllabus_unit
    ADD CONSTRAINT fk_syllabus_unit_syllabus FOREIGN KEY (syllabus_id) REFERENCES syllabus (id)
        ON DELETE CASCADE;

-- ---------------------------------------------------------- syllabus topics

CREATE TABLE syllabus_topic (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    syllabus_id BIGINT       NOT NULL,
    unit_id     BIGINT       NOT NULL,
    title       VARCHAR(500) NOT NULL,
    position    INT          NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_syllabus_topic_position ON syllabus_topic (unit_id, position);
CREATE INDEX idx_syllabus_topic_syllabus ON syllabus_topic (syllabus_id);
CREATE INDEX idx_syllabus_topic_unit ON syllabus_topic (unit_id);

ALTER TABLE syllabus_topic
    ADD CONSTRAINT fk_syllabus_topic_syllabus FOREIGN KEY (syllabus_id) REFERENCES syllabus (id)
        ON DELETE CASCADE;
ALTER TABLE syllabus_topic
    ADD CONSTRAINT fk_syllabus_topic_unit FOREIGN KEY (unit_id) REFERENCES syllabus_unit (id)
        ON DELETE CASCADE;

-- -------------------------------------------------------- syllabus subtopics

CREATE TABLE syllabus_subtopic (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    syllabus_id BIGINT       NOT NULL,
    topic_id    BIGINT       NOT NULL,
    title       VARCHAR(500) NOT NULL,
    position    INT          NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_syllabus_subtopic_position ON syllabus_subtopic (topic_id, position);
CREATE INDEX idx_syllabus_subtopic_syllabus ON syllabus_subtopic (syllabus_id);
CREATE INDEX idx_syllabus_subtopic_topic ON syllabus_subtopic (topic_id);

ALTER TABLE syllabus_subtopic
    ADD CONSTRAINT fk_syllabus_subtopic_syllabus FOREIGN KEY (syllabus_id) REFERENCES syllabus (id)
        ON DELETE CASCADE;
ALTER TABLE syllabus_subtopic
    ADD CONSTRAINT fk_syllabus_subtopic_topic FOREIGN KEY (topic_id) REFERENCES syllabus_topic (id)
        ON DELETE CASCADE;

-- --------------------------------------------------- learning outcomes

-- Outcomes may hang off the syllabus as a whole or be attached to a unit.
CREATE TABLE syllabus_learning_outcome (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    syllabus_id BIGINT        NOT NULL,
    unit_id     BIGINT,
    statement   VARCHAR(1000) NOT NULL,
    position    INT           NOT NULL,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_syllabus_outcome_position ON syllabus_learning_outcome (syllabus_id, position);
CREATE INDEX idx_syllabus_outcome_syllabus ON syllabus_learning_outcome (syllabus_id);
CREATE INDEX idx_syllabus_outcome_unit ON syllabus_learning_outcome (unit_id);

ALTER TABLE syllabus_learning_outcome
    ADD CONSTRAINT fk_syllabus_outcome_syllabus FOREIGN KEY (syllabus_id) REFERENCES syllabus (id)
        ON DELETE CASCADE;
ALTER TABLE syllabus_learning_outcome
    ADD CONSTRAINT fk_syllabus_outcome_unit FOREIGN KEY (unit_id) REFERENCES syllabus_unit (id)
        ON DELETE CASCADE;