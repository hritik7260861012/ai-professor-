-- V5__ai_content_generation.sql -- Phase 5: AI content generation
-- Additive only. V1-V4 are never modified.
-- Compatible with PostgreSQL 15+ (and Supabase) and H2 in PostgreSQL mode.
--
-- Generation is permitted only from an APPROVED syllabus (enforced in
-- SyllabusContentService, not here). Every artifact records the syllabus
-- and the syllabus VERSION it was generated from, so content derived from a
-- superseded version can be detected as OUTDATED.

-- ------------------------------------------------------------ generation jobs

CREATE TABLE ai_generation_job (
    id                   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Owner. Always taken from the security principal; the client never
    -- supplies a user id.
    requested_by         BIGINT       NOT NULL,

    -- Generation source. Restricting to the syllabus id keeps the
    -- class/subject/semester reachable through it, so they are not
    -- duplicated here.
    syllabus_id          BIGINT       NOT NULL,
    -- Denormalised so "is this stale?" never needs a join, and so the
    -- original source is preserved even if the syllabus is deleted.
    syllabus_version     INT          NOT NULL,

    -- NULL means the request spans the whole approved syllabus rather than
    -- one unit.
    unit_id              BIGINT,

    content_type         VARCHAR(40)  NOT NULL,
    language             VARCHAR(20)  NOT NULL,
    detail_level         VARCHAR(20)  NOT NULL,
    difficulty           VARCHAR(20)  NOT NULL,
    -- Number of questions/slides requested. Always 1 for notes and study
    -- material, which are not countable.
    item_count           INT          NOT NULL DEFAULT 1,
    -- Optional free text from the teacher, length-capped in the service.
    instructions         VARCHAR(1000),

    -- QUEUED / RUNNING / COMPLETED / FAILED / CANCELLED
    status               VARCHAR(20)  NOT NULL DEFAULT 'QUEUED',
    -- Bounded count of provider attempts actually made.
    attempt_count        INT          NOT NULL DEFAULT 0,
    -- Safe, teacher-facing summary. Never contains the API key or the
    -- full prompt.
    error_code           VARCHAR(40),
    error_message        VARCHAR(500),

    -- Provider metadata for diagnosis. Never a credential.
    provider_name        VARCHAR(40),
    model_name           VARCHAR(80),

    -- Set on COMPLETED; links to the artifact this job produced.
    content_id           BIGINT,

    created_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at           TIMESTAMP,
    completed_at         TIMESTAMP,
    updated_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ai_job_owner ON ai_generation_job (requested_by);
CREATE INDEX idx_ai_job_status ON ai_generation_job (status);
CREATE INDEX idx_ai_job_syllabus ON ai_generation_job (syllabus_id);
-- Supports the per-user daily quota count without a full scan.
CREATE INDEX idx_ai_job_owner_created ON ai_generation_job (requested_by, created_at);

ALTER TABLE ai_generation_job
    ADD CONSTRAINT fk_ai_job_requester FOREIGN KEY (requested_by) REFERENCES app_user (id);
ALTER TABLE ai_generation_job
    ADD CONSTRAINT fk_ai_job_syllabus FOREIGN KEY (syllabus_id) REFERENCES syllabus (id);
ALTER TABLE ai_generation_job
    ADD CONSTRAINT fk_ai_job_unit FOREIGN KEY (unit_id) REFERENCES syllabus_unit (id);

ALTER TABLE ai_generation_job
    ADD CONSTRAINT ck_ai_job_status CHECK (
        status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED', 'CANCELLED'));
ALTER TABLE ai_generation_job
    ADD CONSTRAINT ck_ai_job_content_type CHECK (content_type IN (
        'UNIT_NOTES', 'TEACHER_STUDY_MATERIAL', 'PPT_SLIDES',
        'ASSIGNMENTS_QUESTIONS', 'MCQS', 'QUICK_REVISION'));
ALTER TABLE ai_generation_job
    ADD CONSTRAINT ck_ai_job_language CHECK (language IN ('ENGLISH', 'HINDI', 'HINGLISH'));
ALTER TABLE ai_generation_job
    ADD CONSTRAINT ck_ai_job_detail_level CHECK (detail_level IN ('CONCISE', 'STANDARD', 'DETAILED'));
ALTER TABLE ai_generation_job
    ADD CONSTRAINT ck_ai_job_difficulty CHECK (difficulty IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED'));
ALTER TABLE ai_generation_job
    ADD CONSTRAINT ck_ai_job_item_count CHECK (item_count BETWEEN 1 AND 100);
ALTER TABLE ai_generation_job
    ADD CONSTRAINT ck_ai_job_attempts CHECK (attempt_count >= 0);

-- ---------------------------------------------------------- generated content

CREATE TABLE generated_content (
    id                 BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Provenance. job_id may be NULL for content a teacher edits by hand.
    job_id             BIGINT,
    syllabus_id        BIGINT    NOT NULL,
    syllabus_version   INT       NOT NULL,
    unit_id            BIGINT,

    content_type       VARCHAR(40) NOT NULL,
    language           VARCHAR(20) NOT NULL,

    title              VARCHAR(300) NOT NULL,
    -- Human-readable body (notes, study material, revision summary).
    body               TEXT,
    -- Machine-readable payload for structured types (MCQs, slides,
    -- question sets). Stored once here rather than in per-type tables so
    -- the large text is never duplicated across tables.
    structured_json    TEXT,

    -- STUDENT content is releasable; TEACHER content (study material and
    -- answer keys) never is, regardless of review status.
    audience           VARCHAR(20) NOT NULL,
    -- True when the body contains an answer key or marking guidance.
    contains_answer_key BOOLEAN   NOT NULL DEFAULT FALSE,

    -- DRAFT / IN_REVIEW / APPROVED / REJECTED / OUTDATED
    review_status      VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    -- Set explicitly by the teacher; required before students can read it.
    released_to_students BOOLEAN  NOT NULL DEFAULT FALSE,

    reviewed_by        BIGINT,
    reviewed_at        TIMESTAMP,
    rejection_reason   VARCHAR(500),

    provider_name      VARCHAR(40),
    model_name         VARCHAR(80),

    created_at         TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_content_syllabus ON generated_content (syllabus_id);
CREATE INDEX idx_content_status ON generated_content (review_status);
CREATE INDEX idx_content_unit ON generated_content (unit_id);
CREATE INDEX idx_content_job ON generated_content (job_id);

